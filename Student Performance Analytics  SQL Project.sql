SELECT RANK() OVER(ORDER BY AVG(a.score) DESC) AS course_rank,
       c.course_name,
       COUNT(DISTINCT e.student_id) AS number_of_students,
       ROUND(AVG(a.score),2) AS average_score,
       ROUND(SUM(CASE WHEN a.score >= 50 THEN 1 ELSE 0 END)*100.0
       / COUNT(a.score),2) AS pass_percentage,
       ROUND(AVG(att.attendance_pct),2) AS average_attendance
FROM courses c
LEFT JOIN enrollments e ON c.course_id = e.course_id
LEFT JOIN assessments a ON c.course_id = a.course_id
LEFT JOIN (
    SELECT course_id, student_id,
           SUM(CASE WHEN status = 'Present' THEN 100.0 ELSE 0 END)
           / COUNT(*) AS attendance_pct
    FROM attendance
    GROUP BY course_id, student_id
) att ON c.course_id = att.course_id
GROUP BY c.course_id, c.course_name
ORDER BY course_rank;