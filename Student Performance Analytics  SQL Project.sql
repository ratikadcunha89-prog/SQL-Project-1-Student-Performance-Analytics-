DROP DATABASE IF EXISTS Student_Performance;
CREATE DATABASE Student_Performance CHARACTER SET utf8mb4;
USE Student_Performance;

CREATE TABLE students (
    student_id      INT PRIMARY KEY AUTO_INCREMENT,
    student_name    VARCHAR(100) NOT NULL,
    gender          VARCHAR(10),
    city            VARCHAR(50),
    enrollment_date DATE
);

CREATE TABLE courses (
    course_id   INT PRIMARY KEY AUTO_INCREMENT,
    course_name VARCHAR(100) NOT NULL,
    category    VARCHAR(50),
    duration    INT COMMENT 'Duration in weeks'
);

CREATE TABLE enrollments (
    enrollment_id   INT PRIMARY KEY AUTO_INCREMENT,
    student_id      INT NOT NULL,
    course_id       INT NOT NULL,
    enrollment_date DATE,
    status          VARCHAR(20) COMMENT 'Active / Completed / Dropped',
    FOREIGN KEY (student_id) REFERENCES students(student_id),
    FOREIGN KEY (course_id)  REFERENCES courses(course_id)
);

CREATE TABLE attendance (
    attendance_id   INT PRIMARY KEY AUTO_INCREMENT,
    student_id      INT NOT NULL,
    course_id       INT NOT NULL,
    attendance_date DATE,
    status          VARCHAR(10) COMMENT 'Present / Absent',
    FOREIGN KEY (student_id) REFERENCES students(student_id),
    FOREIGN KEY (course_id)  REFERENCES courses(course_id)
);

CREATE TABLE assessments (
    assessment_id   INT PRIMARY KEY AUTO_INCREMENT,
    student_id      INT NOT NULL,
    course_id       INT NOT NULL,
    assessment_type VARCHAR(30) COMMENT 'Quiz / Assignment / Midterm / Final',
    score           INT COMMENT '0-100',
    assessment_date DATE,
    FOREIGN KEY (student_id) REFERENCES students(student_id),
    FOREIGN KEY (course_id)  REFERENCES courses(course_id)
);

