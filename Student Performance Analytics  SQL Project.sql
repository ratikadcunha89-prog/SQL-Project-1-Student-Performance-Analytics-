-- Find the top 3 students in every course using RANK().

WITH student_scores AS (		/*First CTE*/
    SELECT
        a.course_id,
        a.student_id,
        AVG(a.score) AS average_score
    FROM assessments a
    GROUP BY a.course_id, a.student_id
),
ranked_students AS (     /*Second CTE*/
    SELECT
        c.course_name,
        s.student_id,
        s.student_name,
        ss.average_score,
        RANK() OVER (
            PARTITION BY ss.course_id
            ORDER BY ss.average_score DESC
        ) AS student_rank
    FROM student_scores ss    /*First CTE alias is ss*/
    JOIN students s
        ON ss.student_id = s.student_id
    JOIN courses c
        ON ss.course_id = c.course_id
)
SELECT
    course_name,
    student_id,
    student_name,
    ROUND(average_score, 2) AS average_score,
    student_rank
FROM ranked_students
WHERE student_rank <= 3
ORDER BY course_name, student_rank;


