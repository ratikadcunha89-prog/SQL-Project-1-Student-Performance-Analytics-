    c.course_id,
    c.course_name,
    COUNT(a.assessment_id) AS total_assessments,

    SUM(CASE 
        WHEN a.score >= 50 THEN 1 
        ELSE 0 
        END
         ) AS passed_assessments,

    SUM(CASE 
        WHEN a.score < 50 THEN 1 
        ELSE 0 
    END) AS failed_assessments,

    ROUND(
        SUM(CASE 
            WHEN a.score >= 50 THEN 1 
            ELSE 0 
        END) * 100.0 
        / COUNT(a.assessment_id), 2) AS pass_percentage

FROM courses c
JOIN assessments a
    ON c.course_id = a.course_id
GROUP BY c.course_id, c.course_name;


