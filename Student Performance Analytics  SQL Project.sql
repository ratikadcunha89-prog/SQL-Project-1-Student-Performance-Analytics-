-- Identify students whose latest assessment score is higher than their previous assessment score. Use the LAG() window function.

SELECT s.student_id, s.student_name,
       x.previous_score, x.score AS latest_score
FROM students AS s
JOIN (
    SELECT student_id, score,
           LAG(score) OVER (
               PARTITION BY student_id
               ORDER BY assessment_date
           ) AS previous_score,
           ROW_NUMBER() OVER (
               PARTITION BY student_id
               ORDER BY assessment_date DESC
           ) AS rn
    FROM assessments
) AS x
ON s.student_id = x.student_id
WHERE x.rn = 1
AND x.score > x.previous_score;

-- Rank students within each course based on their average assessment score. Use RANK() and PARTITION BY. Return the top 3 students from each course.

SELECT *
FROM (
    SELECT c.course_name, s.student_name,
           AVG(a.score) AS average_score,
           RANK() OVER (
               PARTITION BY c.course_id
               ORDER BY AVG(a.score) DESC
           ) AS student_rank
    FROM courses AS c
    JOIN assessments AS a
        ON c.course_id = a.course_id
    JOIN students AS s
        ON a.student_id = s.student_id
    GROUP BY c.course_id, c.course_name,
             s.student_id, s.student_name
) AS ranked_students
WHERE student_rank <= 3;

