SELECT student_id, student_name,
       ROUND(attendance_pct, 2) AS attendance_pct,
       ROUND(avg_score, 2) AS avg_score
FROM student_stats
ORDER BY attendance_pct DESC;

-- 1b) Pearson correlation coefficient (r)
SELECT ROUND((AVG(attendance_pct * avg_score) - AVG(attendance_pct) * AVG(avg_score))
       / (STDDEV_POP(attendance_pct) * STDDEV_POP(avg_score)), 2) AS correlation_r
FROM student_stats;

-- 1c) Average score: attendance below 75% vs 75% and above
SELECT IF(attendance_pct < 75, 'Below 75%', '75% and above') AS attendance_group,
       COUNT(*) AS students,
       ROUND(AVG(avg_score), 2) AS avg_score
FROM student_stats
GROUP BY attendance_group;

