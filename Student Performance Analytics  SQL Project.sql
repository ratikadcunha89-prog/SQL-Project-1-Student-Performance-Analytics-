-- BONUS SETUP (run once, used by Bonus 1 and Bonus 2)
-- One row per student: overall attendance % and overall average score.
-- Attendance and scores are summarised separately and then joined,
-- so rows are not multiplied.
-- ============================================================
CREATE OR REPLACE VIEW student_stats AS
SELECT s.student_id, s.student_name, a.attendance_pct, p.avg_score
FROM students s
JOIN (SELECT student_id, 100 * AVG(status = 'Present') AS attendance_pct
      FROM attendance GROUP BY student_id) a ON a.student_id = s.student_id
JOIN (SELECT student_id, AVG(score) AS avg_score
      FROM assessments GROUP BY student_id) p ON p.student_id = s.student_id;

